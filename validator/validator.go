package validator

import (
	"context"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
	"time"

	"github.com/fatih/color"
	"github.com/galalen/ckad-trainer/checks"
	"github.com/galalen/ckad-trainer/config"
	"github.com/galalen/ckad-trainer/scenario"
)

func ValidateScenarios(cfg *config.Config) error {
	if !cfg.ValidateAll && cfg.ValidateScenario == 0 {
		return fmt.Errorf("must specify --scenario or --all flag")
	}

	if !fileExists(cfg.OutputDir) {
		return fmt.Errorf("scenarios directory %s does not exist", cfg.OutputDir)
	}

	v := &validator{
		run:          checks.KubectlRunner,
		timeout:      time.Duration(cfg.CheckTimeout) * time.Second,
		allowScripts: cfg.AllowScripts,
	}

	if !cfg.ValidateAll {
		dir := filepath.Join(cfg.OutputDir, scenario.DirName(cfg.ValidateScenario))
		if !fileExists(dir) {
			return fmt.Errorf("scenario %02d does not exist in %s", cfg.ValidateScenario, cfg.OutputDir)
		}
		return v.validate(dir)
	}

	entries, err := scenario.List(cfg.OutputDir)
	if err != nil {
		return fmt.Errorf("error reading scenarios directory: %w", err)
	}

	failures := 0
	for _, e := range entries {
		if err := v.validate(e.Dir); err != nil {
			color.Red("%s: %v", filepath.Base(e.Dir), err)
			failures++
		}
		fmt.Println()
	}

	if failures > 0 {
		return fmt.Errorf("%d of %d scenarios failed validation", failures, len(entries))
	}
	color.Green("All %d scenarios passed", len(entries))
	return nil
}

type validator struct {
	run          checks.Runner
	timeout      time.Duration
	allowScripts bool
}

func (v *validator) validate(dir string) error {
	if scenario.HasJSON(dir) {
		return v.validateChecks(dir)
	}
	return v.validateLegacyScript(dir)
}

func (v *validator) validateChecks(dir string) error {
	s, err := scenario.Load(dir)
	if err != nil {
		return err
	}

	color.New(color.Bold).Printf("%s: %s\n", filepath.Base(dir), s.Title)

	passed := 0
	for i, task := range s.Tasks {
		tr := checks.RunTask(context.Background(), v.run, task, v.timeout)
		if tr.Passed() {
			passed++
			color.Green("  ✓ %d. %s", i+1, task.Text)
			continue
		}

		color.Red("  ✗ %d. %s", i+1, task.Text)
		for _, r := range tr.Results {
			if r.Passed {
				continue
			}
			printFailure(r)
		}
	}

	summary := fmt.Sprintf("  %d/%d tasks passed", passed, len(s.Tasks))
	if passed == len(s.Tasks) {
		color.Green("%s", summary)
		return nil
	}
	color.Yellow("%s", summary)
	return fmt.Errorf("%d tasks failed", len(s.Tasks)-passed)
}

func printFailure(r checks.Result) {
	label := r.Check.Description
	if label == "" {
		label = r.Check.Cmd
	}
	fmt.Printf("      - %s\n", label)

	got := r.Output
	if got == "" {
		got = "(no output)"
	}
	if r.Err != nil && r.Output == "" {
		got = r.Err.Error()
	}
	got = strings.ReplaceAll(got, "\n", "\n          ")

	if r.Check.Expect != "" {
		fmt.Printf("        expected: %s\n", r.Check.Expect)
	}
	fmt.Printf("        got:      %s\n", got)
}

// validateLegacyScript runs validate.sh from scenarios generated by earlier
// versions. These are arbitrary LLM-written bash, so they only run when the
// user opts in with --allow-scripts.
func (v *validator) validateLegacyScript(dir string) error {
	script := filepath.Join(dir, scenario.LegacyScript)
	if !fileExists(script) {
		return fmt.Errorf("no scenario.json or %s found", scenario.LegacyScript)
	}
	if !v.allowScripts {
		return fmt.Errorf("legacy script %s is arbitrary bash; review it and rerun with --allow-scripts, or regenerate the scenario", script)
	}

	color.Yellow("Running legacy validation script %s...", script)
	cmd := exec.Command("/bin/bash", script)
	cmd.Stdout = os.Stdout
	cmd.Stderr = os.Stderr
	if err := cmd.Run(); err != nil {
		return fmt.Errorf("validation failed: %w", err)
	}
	color.Green("%s passed", filepath.Base(dir))
	return nil
}

func fileExists(path string) bool {
	_, err := os.Stat(path)
	return err == nil
}
